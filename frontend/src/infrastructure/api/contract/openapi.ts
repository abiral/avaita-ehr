import { z } from 'zod'
import type { Endpoint } from './types'

type Json = null | boolean | number | string | readonly Json[] | { readonly [k: string]: Json }

const clean = (node: unknown): Json => {
  if (Array.isArray(node)) return node.map(clean)
  if (node && typeof node === 'object') {
    const out: Record<string, Json> = {}
    const rec = node as Record<string, unknown>
    for (const [k, v] of Object.entries(rec)) {
      if (k === '$schema' || (k === 'pattern' && 'format' in rec)) continue
      out[k] = clean(v)
    }
    return out
  }
  return node as Json
}

export const schemaOf = (schema: z.ZodType): Json => clean(z.toJSONSchema(schema, { unrepresentable: 'any' }))

const PROBLEM = { $ref: '#/components/schemas/Problem' }

function operation(e: Endpoint, example: unknown): Json {
  const params = [
    ...Object.keys(e.params ?? {}).map((name) => ({ name, in: 'path', required: true, schema: { type: 'string' } })),
    ...Object.keys(e.query ?? {}).map((name) => ({ name, in: 'query', required: false, schema: { type: 'string' } })),
    ...Object.keys(e.headers ?? {}).map((name) => ({
      name,
      in: 'header',
      required: false,
      schema: { type: 'string' },
    })),
  ]
  const content = e.stream
    ? { 'text/event-stream': { schema: { type: 'string' } } }
    : e.response
      ? { 'application/json': { schema: schemaOf(e.response), example: example as Json } }
      : null
  const responses: Record<string, Json> = {
    [String(e.status)]: content ? { description: e.summary, content } : { description: e.summary },
  }
  if (e.errors.length)
    responses.default = {
      description: `Problem: ${e.errors.join(', ')}`,
      content: { 'application/problem+json': { schema: PROBLEM } },
    }
  const body = e.request
    ? {
        requestBody: {
          required: true,
          content: { 'application/json': { schema: schemaOf(e.request), example: e.body as Json } },
        },
      }
    : {}
  return {
    operationId: e.id,
    tags: [e.group],
    summary: e.summary,
    ...(params.length ? { parameters: params } : {}),
    ...body,
    responses,
  }
}

/** Builds the OpenAPI 3.1 document from the endpoint registry and the recorded examples. */
export function buildOpenApi(endpoints: readonly Endpoint[], examples: Readonly<Record<string, unknown>>): Json {
  const paths: Record<string, Record<string, Json>> = {}
  for (const e of endpoints) {
    paths[e.path] = { ...paths[e.path], [e.method]: operation(e, examples[e.id] ?? null) }
  }
  return {
    openapi: '3.1.0',
    info: {
      title: 'Folio EHR API (draft)',
      version: '0.1.0',
      description:
        'Draft contract owned by the frontend. JSON, camelCase, ISO 8601 UTC timestamps, opaque string ids, cursor pagination ({ items, nextCursor }). Every request carries X-Organization-Id and X-Facility-Id; writes carry X-CSRF-Token. Errors are application/problem+json with a code. Generated by npm run contract:update.',
    },
    servers: [{ url: '/api' }],
    paths,
    components: {
      schemas: {
        Problem: {
          type: 'object',
          required: ['title', 'status', 'code'],
          properties: {
            type: { type: 'string' },
            title: { type: 'string' },
            status: { type: 'integer' },
            code: { type: 'string' },
            fields: { type: 'object', additionalProperties: { type: 'string' } },
          },
        },
      },
      securitySchemes: { session: { type: 'apiKey', in: 'cookie', name: 'folio_session' } },
    },
    security: [{ session: [] }],
  }
}
